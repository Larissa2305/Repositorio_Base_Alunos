# Utilize um loop while e um loop for para contar de 0 até o número que o usuário digitar:

# ------------------------------------------ ESCREVA SEU CÓDIGO ABAIXO -----------------------------------------------------------

# LOOP WHILE

cont = 1
num = int(input('Digite um número: '))
while cont <= num:
    print(cont)
    cont+=1




# LOOP FOR
numero = int(input('Digite um número: '))
for cont in range(numero):
    print(cont)
